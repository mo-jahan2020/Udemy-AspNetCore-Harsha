namespace DIEduDemo.Services;

/// <summary>
/// اینترفیس برای پردازش سفارش.
/// این نشان می‌دهد که چطور در یک پروژه واقعی، قراردادهای بیزینسی را با اینترفیس تعریف می‌کنیم.
/// </summary>
public interface IOrderProcessor
{
    /// <summary>
    /// پردازش یک سفارش فرضی.
    /// </summary>
    /// <param name="orderId">شناسه سفارش</param>
    /// <returns>پیام نتیجه پردازش</returns>
    string ProcessOrder(int orderId);
}
