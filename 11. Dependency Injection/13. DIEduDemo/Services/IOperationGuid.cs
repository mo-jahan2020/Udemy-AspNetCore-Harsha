// ============================================================================
//  IOperationGuid.cs — اینترفیس مشترک برای نمایش تفاوت Lifetimeها
// ----------------------------------------------------------------------------
//  چرا از اینترفیس استفاده می‌کنیم؟
//   - Loose Coupling: کلاس مصرف‌کننده به اینترفیس وابسته است، نه پیاده‌سازی.
//   - Testability: در زمان تست، می‌توانیم یک Mock پیاده‌سازی کنیم.
//   - انعطاف‌پذیری: می‌توانیم پیاده‌سازی را بدون تغییر مصرف‌کننده عوض کنیم.
// ============================================================================

namespace DIEduDemo.Services;

/// <summary>
/// اینترفیس مشترک برای هر سه سرویس با Lifetime متفاوت.
/// هر پیاده‌سازی، یک Guid تولید می‌کند تا بتوانیم در خروجی بفهمیم
/// آیا نمونه جدید ساخته شده یا همان نمونه قبلی بازگردانده شده است.
/// </summary>
public interface IOperationGuid
{
    /// <summary>
    /// شناسه یکتای نمونه ساخته‌شده از سرویس.
    /// اگر این مقدار در دو بار درخواست برابر باشد، یعنی همان نمونه بازگردانده شده.
    /// </summary>
    Guid OperationId { get; }

    /// <summary>
    /// نام Lifetime این سرویس (مثلاً Transient/Scoped/Singleton).
    /// برای نمایش در خروجی استفاده می‌شود.
    /// </summary>
    string LifetimeName { get; }
}

// ----------------------------------------------------------------------------
// سه اینترفیس مجزا برای هر Lifetime
// ----------------------------------------------------------------------------
// نکته آموزشی: چرا سه اینترفیس جدا؟
// چون اگر هر سه سرویس فقط IOperationGuid را پیاده‌سازی کنند،
// Container نمی‌داند کدام را تزریق کند (مگر با کلیدواژه‌ی [FromKeyedServices]).
// راه ساده‌تر: برای هر Lifetime یک اینترفیس مشتق‌شده تعریف می‌کنیم.

/// <summary>
/// اینترفیس سرویس با Lifetime = Transient
/// </summary>
public interface IOperationTransient : IOperationGuid { }

/// <summary>
/// اینترفیس سرویس با Lifetime = Scoped
/// </summary>
public interface IOperationScoped : IOperationGuid { }

/// <summary>
/// اینترفیس سرویس با Lifetime = Singleton
/// </summary>
public interface IOperationSingleton : IOperationGuid { }
