// ============================================================================
//  INotificationService.cs — اینترفیس برای Keyed Services
// ----------------------------------------------------------------------------
//  Keyed Services (دات‌نت 8 به بعد):
//   - اجازه می‌دهد چند پیاده‌سازی از یک اینترفیس با کلیدهای مختلف ثبت شوند.
//   - سپس با `[FromKeyedServices("key")]` یا `sp.GetKeyedService<T>("key")` بازگردانده می‌شوند.
//   - مناسب برای زمانی که یک قرارداد داریم اما چند پیاده‌سازی متفاوت (Strategy Pattern).
//
//  مثال:
//   - ایمیل: برای اطلاع‌رسانی‌های رسمی
//   - پیامک: برای کدهای تأیید سریع
//   - Push:  برای اعلان‌های درون‌برنامه‌ای
// ============================================================================

namespace DIEduDemo.Services;

/// <summary>
/// اینترفیس مشترک برای همه‌ی سرویس‌های اعلان.
/// هر پیاده‌سازی، روش خاص خودش را برای ارسال پیام دارد.
/// </summary>
public interface INotificationService
{
    /// <summary>
    /// نام کانال اعلان (مثلاً "Email" یا "SMS")
    /// </summary>
    string ChannelName { get; }

    /// <summary>
    /// ارسال یک پیام به کاربر
    /// </summary>
    /// <param name="recipient">گیرنده (ایمیل، شماره موبایل، ...)</param>
    /// <param name="message">متن پیام</param>
    /// <returns>نتیجه ارسال</returns>
    string Send(string recipient, string message);
}
