// ====================================================================
// فایل Program.cs - نقطه شروع برنامه ASP.NET Core
// ====================================================================
// در این فایل تمام تنظیمات و پیکربندی‌های برنامه انجام می‌شود.
// این برنامه شامل MVC، Razor Pages، Blazor Server و Minimal API است.
// ====================================================================

// ایجاد Builder برای ساخت برنامه
// WebApplication.CreateBuilder تمام تنظیمات پیش‌فرض را بارگذاری می‌کند
var builder = WebApplication.CreateBuilder(args);

// ====================================================================
// ثبت سرویس‌ها (Dependency Injection)
// ====================================================================

// ثبت سرویس‌های MVC شامل کنترلرها و ویوها
// AddControllersWithViews هم کنترلرها و هم Razor Views را فعال می‌کند
builder.Services.AddControllersWithViews();

// ثبت سرویس‌های Razor Pages
// با این تنظیم، فایل‌های موجود در پوشه Pages به عنوان Razor Page شناخته می‌شوند
builder.Services.AddRazorPages();

// ثبت سرویس‌های Blazor Server
// با این تنظیم، کامپوننت‌های Blazor (.razor) در برنامه قابل استفاده هستند
// Blazor Server از WebSocket برای ارتباط بلادرنگ با مرورگر استفاده می‌کند
builder.Services.AddServerSideBlazor();

// ====================================================================
// ساخت برنامه
// ====================================================================
var app = builder.Build();

// ====================================================================
// تنظیم Middleware (میان‌افزارها)
// ====================================================================

// فعال‌سازی فایل‌های استاتیک
// این میان‌افزار اجازه دسترسی به فایل‌های پوشه wwwroot را می‌دهد
// بدون این خط، فایل sample.pdf از طریق مرورگر قابل دسترسی نخواهد بود
app.UseStaticFiles();

// فعال‌سازی مسیریابی (Routing)
// این میان‌افزار درخواست‌های ورودی را به کنترلرها/صفحات مناسب هدایت می‌کند
app.UseRouting();

// ====================================================================
// تعریف مسیرها (Endpoints)
// ====================================================================

// تعریف مسیر پیش‌فرض MVC
// الگوی {controller=Home}/{action=Index}/{id?} یعنی:
// - کنترلر پیش‌فرض: HomeController
// - اکشن پیش‌فرض: Index
// - id اختیاری است
app.MapControllerRoute(
    name: "default",
    pattern: "{controller=Home}/{action=Index}/{id?}");

// فعال‌سازی Razor Pages
// این خط تمام Razor Page ها را در مسیر /Pages قابل دسترسی می‌کند
app.MapRazorPages();

// فعال‌سازی Blazor Hub
// Blazor Server از SignalR استفاده می‌کند
// MapBlazorHub یک endPoint برای اتصال WebSocket ایجاد می‌کند
app.MapBlazorHub();

// ====================================================================
// روش ۱۳: دانلود با Minimal API
// ====================================================================
// Minimal API یک روش جدید در .NET 6+ است که بدون نیاز به کنترلر
// می‌توانید Endpoint تعریف کنید. این روش برای API های ساده بسیار مناسب است.
//
// نکته آموزشی:
// - Results.File() یک پاسخ فایل برمی‌گرداند (مشابه FileResult در کنترلر)
// - می‌توانید مستقیماً بایت‌های فایل را بخوانید و برگردانید
// - این روش نیازی به کنترلر ندارد
// ====================================================================
app.MapGet("/api/download/minimal", (IWebHostEnvironment env) =>
{
    // ساختن مسیر کامل فایل با استفاده از WebRootPath
    var filePath = Path.Combine(env.WebRootPath, "sample.pdf");

    // بررسی وجود فایل - اگر فایل وجود نداشت، 404 برمی‌گردانیم
    if (!System.IO.File.Exists(filePath))
        return Results.NotFound("فایل مورد نظر یافت نشد!");

    // خواندن تمام بایت‌های فایل
    var fileBytes = System.IO.File.ReadAllBytes(filePath);

    // برگرداندن فایل با نام سفارشی
    // پارامتر سوم نام فایلی است که کاربر دانلود می‌کند
    return Results.File(fileBytes, "application/pdf", "minimal-api-download.pdf");
})
.WithName("MinimalDownload") // نام این Endpoint (برای لینک‌دهی)
.WithSummary("دانلود فایل با Minimal API"); // توضیح کوتاه

// ====================================================================
// اجرای برنامه
// ====================================================================
// app.Run برنامه را شروع کرده و منتظر درخواست‌های ورودی می‌ماند
app.Run();